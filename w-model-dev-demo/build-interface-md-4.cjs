W('| 角色 | 签发场景 | 关键 claim | 失效场景 |\n');
W('|---|---|---|---|\n');
W('| reader | POST /users 注册成功 / POST /auth/login | `sub=userId`, `role=reader` | 用户被禁用（V2）/ 主动登出（V2） |\n');
W('| blogger | POST /bloggers/apply 成功后 / POST /me/bloggers/:id/switch | `sub=bloggerId`, `role=blogger` | 博主被禁用（V2） |\n');
W('| admin | V2 阶段支持（V1 仅占位） | `sub=adminId`, `role=admin` | — |\n\n');
W('**JWT 工具**：`src/shared/auth/jwt.ts`\n\n');
W('- 签发：`signToken({ sub, role }) => string`，使用 `JWT_SECRET`（HS256）\n');
W('- 验证：`verifyToken(token) => { sub, role }`，失败抛 `UNAUTHENTICATED(401)`\n');
W('- TTL：86400s（24h）；客户端需自行管理刷新（V1 不支持 refresh token）\n\n');
W('### 4.2 鉴权中间件链（authGuard）\n\n');
W('```typescript\n');
W('// src/middleware/auth-guard.middleware.ts\n');
W('function authGuard(req, res, next) {\n');
W('  const header = req.headers.authorization;\n');
W('  if (!header || !header.startsWith("Bearer ")) {\n');
W('    throw new AppError("UNAUTHENTICATED", 401, "Missing Bearer token");\n');
W('  }\n');
W('  const token = header.slice(7);\n');
W('  try {\n');
W('    const payload = verifyToken(token);\n');
W('    req.user = { id: payload.sub, role: payload.role };\n');
W('    next();\n');
W('  } catch (e) {\n');
W('    throw new AppError("UNAUTHENTICATED", 401, "Invalid or expired token");\n');
W('  }\n');
W('}\n');
W('```\n\n');
W('**roleGuard**：在 authGuard 之后执行，校验 `req.user.role ∈ 允许角色集`。不通过抛 `FORBIDDEN(403)`。\n\n');
W('### 4.3 限流策略（继承 INTF-020）\n\n');
